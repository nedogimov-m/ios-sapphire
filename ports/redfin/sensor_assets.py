"""Private native ADSP firmware and persist-registry packaging for Redfin.

No firmware or calibration is supplied here. Inputs must be the actual bounded
readonly captures; provenance and all generated bytes remain outside git.
"""
import hashlib
import json
import math
from pathlib import Path
import re
import struct

from memory import _tree
import wifi_fw_blob as blob
from wifi_firmware import read_regular, require

BASE, MEMORY, MAX_BYTES = 0x89200000, 0x2800000, 32 * 1024 * 1024
CONTRACT = (1, 1, 2, 443, 429, 3, 0, 2, 384, 384)


def varint(value):
    require(type(value) is int and 0 <= value < 1 << 64, 'invalid protobuf integer')
    result = bytearray()
    while value > 127:
        result.append((value & 127) | 128)
        value >>= 7
    return bytes(result + bytes([value]))


def field(number, data):
    return varint(number * 8 + 2) + varint(len(data)) + data


def registry_requests(directory):
    """Preserve actual item types/versions and expand the persisted child links.

    Registry writes merge named items. Large groups are fragmented on item
    boundaries, including nested subgroups; no value is dropped or truncated.
    The native client reads each fragment back before allowing sensor use.
    """
    directory = Path(directory)
    groups = {}
    # Current registry takes precedence over the actual factory fallback.
    for subdir in ('factory_data', 'registry'):
        for path in sorted((directory / subdir).glob('*')):
            if not path.is_file() or path.is_symlink():
                continue
            try:
                data = json.loads(read_regular(path, 65536))
            except (ValueError, UnicodeDecodeError):
                continue  # Captured non-JSON metadata is not a registry group.
            require(type(data) is dict and data, 'invalid native registry JSON')
            for name, items in data.items():
                require(re.fullmatch(r'[A-Za-z0-9_.-]{1,100}', name) and type(items) is dict,
                        'invalid registry group')
                groups[name] = items
    require(1 <= len(groups) <= 256, 'missing/oversized actual registry')
    referenced = set()

    def entries(name, stack=()):
        require(name in groups and name not in stack and len(stack) < 16, 'missing/cyclic registry subgroup')
        result = []
        for key, item in groups[name].items():
            if key == 'owner':
                continue
            require(re.fullmatch(r'[A-Za-z0-9_./-]{1,160}', key) and type(item) is dict,
                    'invalid registry item')
            require(set(item) <= {'type', 'version', 'ver', 'data'} and 'type' in item and 'data' in item and
                    not ('ver' in item and 'version' in item),
                    'unknown registry item schema')
            version = int(item.get('ver', item.get('version', 0)))
            require(0 <= version <= 0xffffffff, 'registry version outside fixed32')
            prefix = field(1, key.encode()) + b'\x15' + struct.pack('<I', version)
            kind, value = item['type'], item['data']
            if kind == 'grp':
                child = name + '.' + key
                referenced.add(child)
                children = entries(child, stack + (name,))
                # A subgroup may itself span several native requests.
                batches, batch = [], b''
                for entry in children:
                    if batch and len(prefix) + len(field(10, batch + entry)) > 760:
                        batches.append(batch)
                        batch = b''
                    batch += entry
                if batch:
                    batches.append(batch)
                for batch in batches:
                    result.append(field(3, prefix + field(10, batch)))
                continue
            if kind == 'str':
                require(type(value) is str and len(value.encode()) <= 512, 'invalid registry string')
                encoded = field(11, value.encode())
            elif kind == 'flt':
                value = float(value)
                require(math.isfinite(value), 'nonfinite registry float')
                encoded = b'\x65' + struct.pack('<f', value)
            elif kind == 'int':
                value = int(value)
                require(-(1 << 63) <= value < 1 << 63, 'registry sfixed64 overflow')
                encoded = b'\x69' + struct.pack('<q', value)
            else:
                raise ValueError('unknown actual registry type')
            result.append(field(3, prefix + encoded))
        return result

    expanded = {name: entries(name) for name in groups}
    requests = []
    # Store each real named group, including direct child group reads used by SEE.
    for name, items in sorted(expanded.items()):
        prefix, batch = field(1, name.encode()), b''
        for item in items:
            require(len(prefix + field(2, item)) <= 936, 'registry item exceeds native QMI request')
            if batch and len(prefix + field(2, batch + item)) > 936:
                requests.append(prefix + field(2, batch))
                batch = b''
            batch += item
        if batch:
            requests.append(prefix + field(2, batch))
    require(1 <= len(requests) <= 400, 'native registry request count outside bound')
    return requests, len(groups)


def native_contract(dtb):
    nodes, fixed = _tree(dtb)
    words = lambda *v: struct.pack('>' + 'I' * len(v), *v)
    def need(path, key, value):
        require(nodes.get(path, {}).get(key) == value, 'native ADSP FDT mismatch: ' + path + ' ' + key)
    adsp, smp = '/soc/qcom,lpass@3000000', '/soc/qcom,smp2p-adsp'
    need(adsp, 'compatible', b'qcom,pil-tz-generic\0')
    need(adsp, 'qcom,pas-id', words(1))
    need(adsp, 'qcom,firmware-name', b'adsp\0')
    need(adsp, 'qcom,signal-aop', b'')
    need(smp, 'qcom,smem', words(443, 429))
    need(smp, 'qcom,remote-pid', words(2))
    handles = {p.get('phandle'): path for path, p in nodes.items() if p.get('phandle')}
    region = handles.get(nodes[adsp].get('memory-region'))
    require(region and region.startswith('/reserved-memory/'), 'ADSP reservation reference missing')
    need(region, 'reg', struct.pack('>QQ', BASE, MEMORY))
    need(region, 'no-map', b'')
    require('reusable' not in nodes[region], 'ADSP reservation is reusable')
    require(all(not (a < BASE + MEMORY and BASE < a + n) for a, n in fixed), 'ADSP overlaps FDT fixed range')
    for path, p in nodes.items():
        if path.startswith('/reserved-memory/') and path != region and 'reg' in p:
            require(len(p['reg']) % 16 == 0, 'unknown reserved-memory cells')
            for a, n in struct.iter_unpack('>QQ', p['reg']):
                require(not (a < BASE + MEMORY and BASE < a + n), 'ADSP reservation overlap')
    for suffix, name in (('lcxlvl', b'lcx.lvl\0'), ('lmxlvl', b'lmx.lvl\0')):
        need('/soc/rsc@18200000/rpmh-regulator-' + suffix, 'qcom,resource-name', name)
    ipcc = nodes[smp].get('mboxes', b'')
    require(len(ipcc) == 12 and ipcc[4:] == words(3, 2) and
            nodes.get(handles.get(ipcc[:4]), {}).get('reg') == words(0x408000, 0x1000),
            'ADSP notification route differs')
    return CONTRACT


def pack(capture, registry, dtb):
    native_contract(dtb)
    capture = Path(capture)
    operations = json.loads(read_regular(capture / 'operations.json', 4 * 1024 * 1024))
    require(type(operations) is list, 'missing firmware extraction provenance')
    records, provenance = [], {}
    def asset(name):
        path = '/firmware/' + name
        matches = [x['result'] for x in operations if x.get('operation') == 'extract' and x.get('path') == path]
        require(len(matches) == 1 and matches[0].get('status') == 'ok' and
                matches[0].get('needs_recovery') is False, 'missing/unclean native asset ' + name)
        data = read_regular(capture / 'assets' / ('firmware__' + name), 16 * 1024 * 1024)
        require(hashlib.sha256(data).hexdigest() == matches[0].get('sha256') and
                len(data) == matches[0]['file']['bytes'], 'native asset hash/length mismatch')
        provenance[name] = matches[0]['sha256']
        return data
    mdt = asset('adsp.mdt')
    require(mdt[:7] == b'\x7fELF\x01\x01\x01' and len(mdt) <= 16384, 'invalid native ADSP ELF32')
    phoff, = struct.unpack_from('<I', mdt, 28)
    ehsize, phsize, count = struct.unpack_from('<HHH', mdt, 40)
    require(ehsize == 52 and phsize == 32 and 2 <= count <= 64 and phoff == 52 and
            phoff + count * 32 <= len(mdt), 'native ADSP program table differs')
    records.append(('fw/adsp.mdt', mdt))
    for name in ('adsp.b00', 'adsp.b01'):
        records.append(('fw/' + name, asset(name)))
    segments = []
    for i in range(count):
        kind, offset, va, pa, size, memory, flags, alignment = struct.unpack_from('<8I', mdt, phoff + i * 32)
        if kind != 1 or (flags & 0x7000000) == 0x2000000 or not memory:
            continue
        require(BASE <= pa < pa + memory <= BASE + MEMORY and size <= memory and
                all(not (pa < a + n and a < pa + memory) for a, n in segments), 'ADSP load range overlaps/escapes')
        segments.append((pa, memory))
        if size:
            data = asset(f'adsp.b{i:02d}')
            require(len(data) == size, 'ADSP split load length differs')
            records.append((f'fw/adsp.b{i:02d}', data))
    require(segments and min(a for a, _ in segments) == BASE and
            max(a + n for a, n in segments) == BASE + MEMORY, 'ADSP image does not fill native reservation')
    for name in ('adspr.jsn', 'adsps.jsn', 'adspua.jsn'):
        native_bytes = asset(name)
        records.append(('fw/' + name, native_bytes))
        native = json.loads(native_bytes)
        d = native['sr_domain']
        require(d['soc'] == 'msm' and d['domain'] == 'adsp' and d['qmi_instance_id'] == 74 and
                d['subdomain'] in ('root_pd', 'sensor_pd', 'audio_pd'), 'ADSP domain differs')
        for s in native['sr_service']:
            service = s['provider'] + '/' + s['service']
            require(re.fullmatch(r'[a-zA-Z0-9_/-]{1,64}', service), 'invalid ADSP service')
            key = 'pd/' + d['subdomain'] + '/' + service
            records.append((key, struct.pack('<III', 74, int(s['service_data_valid']), int(s['service_data']))))
    requests, groups = registry_requests(registry)
    records += [(f'reg/{i:03d}', data) for i, data in enumerate(requests)]
    require(1 <= len(records) <= 512 and len({n for n, _ in records}) == len(records), 'sensor asset bound/duplicates')
    output = bytearray(64 + 128 * len(records))
    output[:8] = b'RFSSC01\0'
    struct.pack_into('<II', output, 8, 1, len(records))
    for i, (name, data) in enumerate(records):
        encoded = name.encode('ascii')
        require(0 < len(encoded) < 80 and data, 'invalid sensor asset')
        at = 64 + 128 * i
        output[at:at + len(encoded)] = encoded
        struct.pack_into('<QQ', output, at + 80, len(output), len(data))
        output[at + 96:at + 128] = hashlib.sha256(data).digest()
        output += data + bytes(-len(data) % 16)
    struct.pack_into('<Q', output, 16, len(output))
    require(len(output) <= MAX_BYTES, 'ADSP package exceeds bounded source')
    return bytes(output), dict(schema=1, bytes=len(output), sha256=hashlib.sha256(output).hexdigest(),
        files=len(records), registry_groups=groups, registry_fragments=len(requests),
        firmware_sha256=provenance, source_view='raw-vendor_b-base', current_effective_image_proven=False,
        signature_authenticated=False, hardware_started=False)


def insert(payload, data, report):
    info = blob.payload_info(payload, gui_packets=True, firmware_present=True)
    root, maps = info['root'], info['memory_map']
    require(not any(n.name == 'redfin-sensors' for n in root.children), 'duplicate sensor source')
    require(len(data) == report['bytes'] and hashlib.sha256(data).hexdigest() == report['sha256'], 'sensor package pairing differs')
    root.children.append(blob.mkadt.node('redfin-sensors', [
        ('source-path', b'/redfin/firmware/native-sensors.bundle\0'), ('bundle-bytes', blob.mkadt.u64(len(data))),
        ('bundle-sha256', bytes.fromhex(report['sha256'])), ('live-fdt-verified', blob.mkadt.u32(1)),
        ('source-contract', blob.mkadt.u32(*CONTRACT)),
        ('hardware-reg', blob.mkadt.u64(BASE, MEMORY, 0x80900000, 0x200000, 0x1f40000, 0x20000, 0x408000, 0x1000))]))
    pieces = [(a, n, payload[o:o + l]) for a, n, o, l in info['segments']]
    output = bytearray(blob.aligned(blob.HEADER + 32 * len(pieces), 16))
    output[:blob.HEADER] = payload[:blob.HEADER]
    for i, (a, n, part) in enumerate(pieces):
        struct.pack_into('<4Q', output, blob.HEADER + 32 * i, a, n, len(output), len(part))
        output += part + bytes(-len(part) % 16)
    tree = blob.mkadt.adt.serialize(root)
    struct.pack_into('<I', output, 12, len(pieces))
    struct.pack_into('<QQQ', output, 32, len(output), len(tree), info['end'])
    output += tree + bytes(-len(tree) % 16)
    require(len(pieces) < 64 and len(output) <= 128 * 1024 * 1024 and
            info['physical'] + info['end'] - info['virt'] + len(tree) + 16384 < info['physical'] + info['memory'], 'sensor payload exceeds bound')
    return bytes(output)
