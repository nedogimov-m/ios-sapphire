"""Walk the actual CPU-only GMU tables and exercise their ownership boundary.

Firmware payloads are generated by the existing parser fixture. No firmware,
device access, hardware context, SMMU write or cache publication is involved.
"""
import ctypes
import errno
from pathlib import Path
import shutil
import struct
import subprocess
import tempfile
import unittest

from ports.redfin.test_gmu_firmware import CHIP, firmware
from ports.redfin.test_gpu_smmu import Snapshot


RAM_BASE = 0x180000000
RAM_END = 0x200000000
PAGE = 0x1000
SAMPLE_REGIONS = [
    (0x4000, 0x8000, True), (0x144000, 0x13000, True),
    (0x157000, 0x9000, True), (0x60000000, 0x1000, True),
    (0x60001000, 0x5000, False), (0x60006000, 0x1000, True),
]


class Memory(ctypes.Structure):
    _fields_ = [('host', ctypes.c_void_p), ('physical', ctypes.c_uint64),
                ('owned_bytes', ctypes.c_uint64), ('token', ctypes.c_uint64),
                ('gmu_address', ctypes.c_uint32)]


class Node(ctypes.Structure):
    _fields_ = [(name, ctypes.c_uint32) for name in ('level', 'prefix', 'parent', 'slot')]


class Extent(ctypes.Structure):
    _fields_ = [('memory', Memory), ('mapped_bytes', ctypes.c_uint32),
                ('permissions', ctypes.c_uint32)]


class Plan(ctypes.Structure):
    _fields_ = [(name, ctypes.c_uint32) for name in (
        'table_count', 'extent_count', 'mapped_pages', 'mapped_bytes',
        'granule', 'virtual_bits', 'physical_bits', 'mair0')]
    _fields_ += [('root_physical', ctypes.c_uint64), ('table_bytes', ctypes.c_uint64),
                 ('tables', Memory), ('nodes', Node * 40), ('extents', Extent * 18)]


HARNESS = r'''
#include <stdlib.h>
#include <string.h>
#include "redfin_gmu_pagetables.h"

struct host {
    const struct rf_gm_memory *backing, *pool;
    unsigned count, guards, owns, bad, lost, guard_fail, deny;
    uint8_t *revoked;
};
static unsigned metrics[3];

static bool valid(void *argument)
{
    struct host *h = argument;
    if (h->lost) h->bad++;
    h->guards++;
    if (h->guard_fail && h->guards >= h->guard_fail) {
        h->lost = 1;
        h->revoked = malloc((size_t)h->pool->owned_bytes);
        if (!h->revoked) abort();
        memcpy(h->revoked, h->pool->host, (size_t)h->pool->owned_bytes);
    }
    return !h->lost;
}

static bool same(const struct rf_gm_memory *a, const struct rf_gm_memory *b)
{
    return a->host == b->host && a->physical == b->physical &&
        a->owned_bytes == b->owned_bytes && a->token == b->token &&
        a->gmu_address == b->gmu_address;
}

static bool owns(void *argument, const struct rf_gm_memory *memory, unsigned use)
{
    struct host *h = argument;
    bool found = false;
    if (h->lost) h->bad++;
    h->owns++;
    if (use == RF_GM_PT_TABLE_POOL)
        found = same(memory, h->pool);
    if (use == RF_GM_PT_DATA)
        for (unsigned i = 0; i < h->count; i++)
            if (same(memory, &h->backing[i])) found = true;
    if (!found) h->bad++;
    return found && h->owns != h->deny;
}

int host_build(const struct rf_gs_snapshot *snapshot, uint32_t chip,
    const void *image, size_t bytes, const struct rf_gm_memory *backing,
    unsigned count, const struct rf_gm_memory *pool,
    unsigned guard_fail, unsigned deny, unsigned missing, struct rf_gm_pt_plan *out)
{
    struct host h = {0};
    h.backing = backing; h.pool = pool; h.count = count;
    h.guard_fail = guard_fail; h.deny = deny;
    struct rf_gm_memory_owner owner = {&h, valid, owns};
    if (missing & 2) owner.valid = NULL;
    if (missing & 4) owner.owns = NULL;
    int error = rf_gm_pt_build(snapshot, chip, image, bytes, backing, count,
        pool, (missing & 1) ? NULL : &owner, out);
    if (h.revoked) {
        if (memcmp(h.revoked, h.pool->host, (size_t)h.pool->owned_bytes)) h.bad++;
        free(h.revoked);
    }
    metrics[0] = h.guards; metrics[1] = h.owns; metrics[2] = h.bad;
    return error;
}

static bool snapshot_valid(void *context) { return context == NULL; }
static int snapshot_read(void *context, uint32_t at, uint32_t *out)
{
    if (context) return EINVAL;
    *out = 0;
    switch (at) {
    case 0x20: *out = (1u << 30) | (1u << 27) | (11u << 9) | 16; break;
    case 0x24: *out = (2u << 28) | 8; break;
    case 0x28: *out = (1u << 12) | (2u << 8) | (1u << 4) | 1; break;
    case 0x3c: *out = 0x20; break;
    case 0x800: *out = 0x84000004; break;
    case 0x804: *out = 0x84000005; break;
    default:
        if (at >= 0xc00 && at < 0xc40)
            *out = at == 0xc00 ? 0 : at == 0xc04 ? 1 : (2u << 16);
        if (at >= 0x1000 && at < 0x1020) *out = 0x10000;
        if (at >= 0x1800 && at < 0x1820) *out = 1;
        break;
    }
    return 0;
}
int host_snapshot(struct rf_gs_snapshot *out)
{
    const struct rf_gs_ops ops = {NULL, snapshot_valid, snapshot_read};
    return rf_gs_snapshot_run(&ops, RF_GS_CHIP, out);
}
unsigned host_metric(unsigned i) { return i < 3 ? metrics[i] : 999; }
size_t host_size(unsigned i)
{
    const size_t sizes[] = {sizeof(struct rf_gm_pt_plan), sizeof(struct rf_gm_memory),
        sizeof(struct rf_gm_pt_extent), sizeof(struct rf_gm_pt_node),
        sizeof(struct rf_gs_snapshot)};
    return i < 5 ? sizes[i] : 0;
}
int host_memory_valid(const struct rf_gm_memory *m) { return rf_gm_memory_valid(m); }
int host_format(const struct rf_gs_snapshot *s) { return rf_gm_snapshot_format(s); }
'''


class Allocation:
    def __init__(self, size):
        self.size = size
        self.raw = (ctypes.c_uint8 * (size + 32))()
        ctypes.memset(self.raw, 0xA7, len(self.raw))
        self.address = ctypes.addressof(self.raw) + 16

    def content(self):
        return ctypes.string_at(self.address, self.size)


class Fixture:
    def __init__(self, library, blob=None, regions=None, pool_bytes=0x8000):
        self.blob = firmware() if blob is None else blob
        self.image = ctypes.create_string_buffer(self.blob)
        self.regions = SAMPLE_REGIONS if regions is None else regions
        self.snapshot = Snapshot()
        if library.host_snapshot(ctypes.byref(self.snapshot)):
            raise AssertionError('synthetic read-only snapshot failed')
        self.pool_allocation = Allocation(pool_bytes)
        self.pool = Memory(self.pool_allocation.address, RAM_BASE + 0x10000,
                           pool_bytes, 1, 0)
        self.allocations = []
        self.backing = (Memory * len(self.regions))()
        for i, (address, mapped_bytes, _) in enumerate(self.regions):
            owned_bytes = (mapped_bytes + 0x3FFF) & ~0x3FFF
            allocation = Allocation(owned_bytes)
            self.allocations.append(allocation)
            self.backing[i] = Memory(allocation.address, RAM_BASE + 0x200000 * (i + 1),
                                     owned_bytes, 0x100 + i, address)

    def state(self):
        return (bytes(self.pool_allocation.raw), bytes(self.image),
                bytes(self.snapshot), bytes(self.pool), bytes(self.backing),
                tuple(bytes(a.raw) for a in self.allocations))

    def expected_pages(self):
        result = {}
        for address, mapped_bytes, privileged in self.regions:
            allocation = next(m for m in self.backing if m.gmu_address == address)
            for offset in range(0, mapped_bytes, PAGE):
                result[address + offset] = (
                    allocation.physical + offset, 0xE03 if privileged else 0xE43)
        return result


class RedfinGMUPagetableTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.directory = tempfile.TemporaryDirectory()
        root = Path(cls.directory.name)
        (root / 'tables.c').write_text(HARNESS)
        subprocess.run([shutil.which('clang') or 'cc', '-std=c11', '-Wall', '-Wextra',
                        '-Werror', '-shared', '-fPIC', '-I', str(Path(__file__).parent / 'include'),
                        str(root / 'tables.c'), '-o', str(root / 'tables.dylib')],
                       check=True, capture_output=True)
        cls.lib = ctypes.CDLL(str(root / 'tables.dylib'))
        cls.lib.host_build.argtypes = [
            ctypes.POINTER(Snapshot), ctypes.c_uint32, ctypes.c_void_p, ctypes.c_size_t,
            ctypes.POINTER(Memory), ctypes.c_uint, ctypes.POINTER(Memory),
            ctypes.c_uint, ctypes.c_uint, ctypes.c_uint, ctypes.POINTER(Plan)]
        cls.lib.host_snapshot.argtypes = [ctypes.POINTER(Snapshot)]
        cls.lib.host_memory_valid.argtypes = [ctypes.POINTER(Memory)]
        cls.lib.host_format.argtypes = [ctypes.POINTER(Snapshot)]
        cls.lib.host_size.restype = ctypes.c_size_t

    @classmethod
    def tearDownClass(cls):
        cls.directory.cleanup()

    def fixture(self, **kwargs):
        return Fixture(self.lib, **kwargs)

    def build(self, fixture, guard=0, deny=0, missing=0, **overrides):
        output = Plan()
        ctypes.memset(ctypes.byref(output), 0xA5, ctypes.sizeof(output))
        args = dict(snapshot=ctypes.byref(fixture.snapshot), chip=CHIP,
                    image=ctypes.cast(fixture.image, ctypes.c_void_p),
                    bytes=len(fixture.blob), backing=fixture.backing,
                    count=len(fixture.backing), pool=ctypes.byref(fixture.pool),
                    output=ctypes.byref(output))
        args.update(overrides)
        result = self.lib.host_build(args['snapshot'], args['chip'], args['image'],
                                    args['bytes'], args['backing'], args['count'], args['pool'],
                                    guard, deny, missing, args['output'])
        metrics = tuple(self.lib.host_metric(i) for i in range(3))
        self.assertEqual(metrics[2], 0, 'callback or table write followed lost ownership')
        return result, output, metrics

    def rejected(self, fixture, expected=errno.EINVAL, **kwargs):
        before = fixture.state()
        error, output, metrics = self.build(fixture, **kwargs)
        self.assertEqual(error, expected)
        self.assertEqual(bytes(output), b'\xA5' * ctypes.sizeof(output))
        self.assertEqual(fixture.state(), before)
        return metrics

    def walk(self, fixture, plan):
        """Decode bytes using ARM's level indices, without using plan.nodes."""
        pool = fixture.pool_allocation.content()
        physical_mask = ((1 << 36) - 1) & ~(PAGE - 1)
        tables, pages = set(), {}

        def visit(physical, level, prefix):
            self.assertNotIn(physical, tables, 'cycle or shared child table')
            self.assertEqual(physical & (PAGE - 1), 0)
            offset = physical - fixture.pool.physical
            self.assertGreaterEqual(offset, 0)
            self.assertLessEqual(offset + PAGE, plan.table_bytes)
            tables.add(physical)
            for slot in range(512):
                descriptor = struct.unpack_from('<Q', pool, offset + 8 * slot)[0]
                if not descriptor:
                    continue
                self.assertEqual(descriptor & 3, 3, 'no block mappings are allowed')
                address = prefix | (slot << (12 + 9 * (3 - level)))
                target = descriptor & physical_mask
                attributes = descriptor & ~physical_mask
                if level < 3:
                    self.assertEqual(attributes, 3)
                    visit(target, level + 1, address)
                else:
                    self.assertNotIn(address, pages)
                    self.assertIn(attributes, (0xE03, 0xE43))
                    pages[address] = (target, attributes)

        visit(plan.root_physical, 1, 0)
        self.assertEqual(len(tables), plan.table_count)
        self.assertEqual(pages, fixture.expected_pages())
        return pages

    def test_native_image_shape_has_five_tables_and_exactly_43_pages(self):
        for index, kind in enumerate((Plan, Memory, Extent, Node, Snapshot)):
            self.assertEqual(ctypes.sizeof(kind), self.lib.host_size(index))
        f = self.fixture()
        error, plan, metrics = self.build(f)
        self.assertEqual(error, 0)
        self.assertEqual((plan.table_count, plan.extent_count, plan.mapped_pages,
                          plan.mapped_bytes, plan.table_bytes), (5, 6, 43, 0x2B000, 0x5000))
        self.assertEqual((plan.granule, plan.virtual_bits, plan.physical_bits,
                          plan.mair0), (0x1000, 39, 36, 0xF404FF44))
        self.assertEqual(bytes(plan.tables), bytes(f.pool))
        self.assertEqual(plan.root_physical, f.pool.physical)
        self.assertEqual(metrics[1], 7)
        self.walk(f, plan)

    def test_permissions_holes_and_tcm_exclusion_follow_the_native_plan(self):
        f = self.fixture()
        error, plan, _ = self.build(f)
        self.assertEqual(error, 0)
        pages = self.walk(f, plan)
        self.assertEqual({a for a, (_, flags) in pages.items() if flags == 0xE43},
                         set(range(0x60001000, 0x60006000, PAGE)))
        for hole in (0, 0x3000, 0xC000, 0x143000, 0x160000,
                     0x10004000, 0x10007000, 0x5FFFF000, 0x60007000, 0x80000000):
            self.assertNotIn(hole, pages)

    def test_16k_owned_slack_canaries_firmware_and_dma_buffers_are_preserved(self):
        f = self.fixture()
        before = f.state()
        error, plan, _ = self.build(f)
        self.assertEqual(error, 0)
        self.assertEqual(f.pool_allocation.content()[plan.table_bytes:],
                         b'\xA7' * (0x8000 - plan.table_bytes))
        self.assertEqual(bytes(f.pool_allocation.raw[:16]), b'\xA7' * 16)
        self.assertEqual(bytes(f.pool_allocation.raw[-16:]), b'\xA7' * 16)
        self.assertEqual(f.state()[1:], before[1:])
        self.assertEqual([e.memory.owned_bytes for e in plan.extents[:6]],
                         [0x8000, 0x14000, 0xC000, 0x4000, 0x8000, 0x4000])

    def test_backing_order_does_not_change_emitted_tables(self):
        f = self.fixture()
        error, plan, _ = self.build(f)
        self.assertEqual(error, 0)
        first = f.pool_allocation.content()
        f.backing = (Memory * 6)(*reversed(f.backing))
        error, second, _ = self.build(f)
        self.assertEqual(error, 0)
        self.assertEqual(f.pool_allocation.content(), first)
        self.assertEqual([e.memory.gmu_address for e in second.extents[:6]],
                         [address for address, _, _ in SAMPLE_REGIONS])
        self.walk(f, plan)

    def test_distinct_l3_tables_cover_both_sides_of_2m_boundaries(self):
        preallocations = [(0, 0x4000, 1), (0x10004000, 0x4000, 1),
                          (0x1FF000, 0x3000, 1), (0x601FF000, 0x3000, 7)]
        regions = [(0x1FF000, 0x3000, True), (0x601FF000, 0x3000, True),
                   (0x60202000, 0x5000, False), (0x60207000, 0x1000, True)]
        blob = firmware(preallocations, [(0x1FF000, 0x100), (0x10007FDC, 0x18)])
        f = self.fixture(blob=blob, regions=regions)
        error, plan, _ = self.build(f)
        self.assertEqual(error, 0)
        self.assertEqual((plan.table_count, plan.mapped_pages), (7, 12))
        self.walk(f, plan)

    def test_maximum_extent_count_and_sparse_table_budget_are_bounded(self):
        preallocations = [(0x601FF000 + i * 0x400000, 0x2000, 7) for i in range(16)]
        last_end = preallocations[-1][0] + 0x2000
        regions = [(address, size, True) for address, size, _ in preallocations]
        regions += [(last_end, 0x5000, False), (last_end + 0x5000, 0x1000, True)]
        blob = firmware(preallocations, [(0x10007FDC, 0x18)])
        too_small = self.fixture(blob=blob, regions=regions)
        self.assertEqual(self.rejected(too_small, errno.ENOSPC), (0, 0, 0))
        f = self.fixture(blob=blob, regions=regions, pool_bytes=0x24000)
        error, plan, _ = self.build(f)
        self.assertEqual(error, 0)
        self.assertEqual((plan.extent_count, plan.table_count, plan.mapped_pages),
                         (18, 34, 38))
        self.walk(f, plan)
        self.assertEqual(f.pool_allocation.content()[plan.table_bytes:], b'\xA7' * 0x2000)

    def test_missing_arguments_callbacks_and_wrong_chip_do_not_request_ownership(self):
        for argument in ('snapshot', 'image', 'backing', 'pool', 'output'):
            expected = errno.ENOTSUP if argument == 'snapshot' else errno.EINVAL
            metrics = self.rejected(self.fixture(), expected, **{argument: None})
            self.assertEqual(metrics, (0, 0, 0))
        for missing in (1, 2, 4, 7):
            self.assertEqual(self.rejected(self.fixture(), missing=missing), (0, 0, 0))
        for chip in (0, 0x06010001, 0x06020000, 0x06030500):
            self.assertEqual(self.rejected(self.fixture(), chip=chip), (0, 0, 0))

    def test_failed_or_inconsistent_snapshot_never_reaches_the_owner(self):
        mutations = {
            'stable': False, 'map_format_supported': False, 'error': errno.EIO, 'stage': 3,
            'page_bytes': 0x10000, 'global_bytes': 0x10000, 'streams': 0, 'contexts': 9,
            'stage2_contexts': 9, 'sid_bits': 10, 'input_bits': 40,
            'output_bits': 32, 'virtual_bits': 32, 'malformed_routes': 1,
            'id0': (1 << 30) | (1 << 27) | (11 << 9) | 17,
            'id1': (3 << 28) | 8,
            'id2': (1 << 12) | (2 << 8) | (1 << 4) | 15,
        }
        for field, value in mutations.items():
            with self.subTest(field=field):
                f = self.fixture()
                setattr(f.snapshot, field, value)
                self.assertEqual(self.rejected(f, errno.ENOTSUP), (0, 0, 0))
        for bit in (30, 27, 8):
            f = self.fixture()
            f.snapshot.id0 ^= 1 << bit
            self.rejected(f, errno.ENOTSUP)
        f = self.fixture()
        f.snapshot.id2 &= ~(1 << 12)
        self.rejected(f, errno.ENOTSUP)

    def test_firmware_is_reparsed_before_any_pool_write(self):
        for blob in (firmware()[:15], firmware()[:-4]):
            self.assertEqual(self.rejected(self.fixture(blob=blob)), (0, 0, 0))
        self.assertEqual(self.rejected(self.fixture(blob=b'\0' * 16), errno.ENOTSUP),
                         (0, 0, 0))
        f = self.fixture()
        f.image[8:12] = struct.pack('<I', 99)
        self.assertEqual(self.rejected(f, errno.ENOTSUP), (0, 0, 0))

    def test_image_and_output_pointer_arithmetic_is_checked_before_dereference(self):
        pointer_max = (1 << (8 * ctypes.sizeof(ctypes.c_void_p))) - 1
        self.rejected(self.fixture(), image=pointer_max - 8, bytes=16)
        self.rejected(self.fixture(), output=ctypes.cast(pointer_max - 8, ctypes.POINTER(Plan)))

    def test_backing_count_addresses_and_minimum_owned_lengths_must_match(self):
        for count in (0, 5, 7, 19):
            self.assertEqual(self.rejected(self.fixture(), count=count), (0, 0, 0))
        for address in (0, 0x10004000, 0x144000, 0x80000000):
            f = self.fixture()
            f.backing[0].gmu_address = address
            self.rejected(f)
        for index in (0, 4):
            f = self.fixture()
            f.backing[index].owned_bytes = 0x4000
            self.rejected(f)
        f = self.fixture()
        f.pool.gmu_address = 0x4000
        self.rejected(f)

    def test_allocation_ranges_alignment_tokens_and_host_overflow_are_checked(self):
        pointer_max = (1 << (8 * ctypes.sizeof(ctypes.c_void_p))) - 1
        invalid = [('host', None), ('token', 0), ('physical', RAM_BASE - PAGE),
                   ('physical', RAM_END), ('physical', RAM_BASE + 1),
                   ('physical', RAM_END - PAGE), ('owned_bytes', 0),
                   ('owned_bytes', 0x4001), ('owned_bytes', 0x201000),
                   ('host', pointer_max - PAGE)]
        for pool in (False, True):
            for field, value in invalid:
                with self.subTest(pool=pool, field=field, value=value):
                    f = self.fixture()
                    setattr(f.pool if pool else f.backing[0], field, value)
                    self.assertEqual(self.rejected(f), (0, 0, 0))
        self.assertEqual(self.lib.host_memory_valid(None), 0)
        self.assertEqual(self.lib.host_format(None), 0)

    def test_host_physical_and_token_aliases_include_full_allocator_owned_slack(self):
        for source_pool in (False, True):
            for field in ('host', 'physical', 'token'):
                for overlap_slack in (False, True):
                    if field == 'token' and overlap_slack:
                        continue
                    f = self.fixture()
                    source = f.pool if source_pool else f.backing[3]
                    target = f.backing[0]
                    value = getattr(source, field)
                    if overlap_slack:
                        value += source.owned_bytes - PAGE
                    setattr(target, field, value)
                    self.assertEqual(self.rejected(f), (0, 0, 0))
        # A one-page map still owns its complete 16KiB allocator extent.
        f = self.fixture()
        f.backing[0].physical = f.backing[3].physical + PAGE
        self.rejected(f)

    def test_pool_and_dma_allocations_must_not_alias_the_immutable_firmware(self):
        for pool in (False, True):
            f = self.fixture()
            memory = f.pool if pool else f.backing[0]
            memory.host = ctypes.addressof(f.image)
            self.assertEqual(self.rejected(f), (0, 0, 0))

    def test_table_pool_cannot_overwrite_inputs_or_result_metadata(self):
        for argument in ('snapshot', 'backing', 'pool'):
            f = self.fixture()
            f.pool.host = ctypes.addressof(getattr(f, argument))
            self.assertEqual(self.rejected(f), (0, 0, 0))
        f = self.fixture()
        result = Plan()
        f.pool.host = ctypes.addressof(result)
        self.rejected(f, output=ctypes.byref(result))
        self.assertEqual(bytes(result), b'\0' * ctypes.sizeof(result))

    def test_result_publication_cannot_overwrite_tables_dma_or_immutable_inputs(self):
        for address_kind in ('pool', 'data', 'image', 'snapshot', 'backing', 'pool_metadata'):
            f = self.fixture()
            address = {
                'pool': f.pool.host, 'data': f.backing[0].host,
                'image': ctypes.addressof(f.image), 'snapshot': ctypes.addressof(f.snapshot),
                'backing': ctypes.addressof(f.backing), 'pool_metadata': ctypes.addressof(f.pool),
            }[address_kind]
            self.assertEqual(self.rejected(f, output=ctypes.cast(address, ctypes.POINTER(Plan))),
                             (0, 0, 0))

    def test_every_denied_allocation_fails_before_any_pool_write(self):
        for deny in range(1, 8):
            metrics = self.rejected(self.fixture(), errno.EACCES, deny=deny)
            self.assertEqual(metrics[1], deny)

    def test_every_lifetime_revocation_stops_writes_and_preserves_output(self):
        f = self.fixture()
        error, plan, metrics = self.build(f)
        self.assertEqual(error, 0)
        successful_pool = f.pool_allocation.content()
        guards = metrics[0]
        for guard in range(1, guards + 1):
            candidate = self.fixture()
            error, output, stopped = self.build(candidate, guard=guard)
            self.assertEqual(error, errno.ECANCELED)
            self.assertEqual(stopped[0], guard)
            self.assertEqual(bytes(output), b'\xA5' * ctypes.sizeof(output))
            if guard == guards:
                # Finished CPU bytes still cannot be published after a lost lease.
                self.assertEqual(candidate.pool_allocation.content(), successful_pool)
            self.assertEqual(candidate.pool_allocation.content()[plan.table_bytes:],
                             b'\xA7' * (0x8000 - plan.table_bytes))

    def test_a_too_small_pool_is_rejected_before_ownership_or_emission(self):
        f = self.fixture(pool_bytes=0x4000)
        self.assertEqual(self.rejected(f, errno.ENOSPC), (0, 0, 0))


