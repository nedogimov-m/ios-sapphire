HERE = Path(__file__).resolve().parent
BDF = bytes((i * 17 + 3) & 255 for i in range(26328))


def identity(*, chip=0x4320, board=None):
    return (tlv(0x10, struct.pack('<II', chip, 0x4001)) +
            (tlv(0x11, struct.pack('<I', board)) if board is not None else b'') +
            tlv(0x12, struct.pack('<I', 0x400b0000)) + tlv(0x13, struct.pack('<I', 0x33197fff)))


def fields(packet):
    result, at = {}, 7
    while at < len(packet):
        kind, length = packet[at], struct.unpack_from('<H', packet, at + 1)[0]
        if kind in result or at + 3 + length > len(packet):
            raise AssertionError('malformed generated TLV')
        result[kind] = packet[at + 3:at + 3 + length]; at += 3 + length
    if at != len(packet):
        raise AssertionError('trailing generated bytes')
    return result


class WiFiBdfTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        if not shutil.which('cc'):
            raise unittest.SkipTest('host C compiler unavailable')
        cls.temporary = tempfile.TemporaryDirectory(); cls.addClassCleanup(cls.temporary.cleanup)
        directory = Path(cls.temporary.name)
        source = r'''
#include "wifi_qmi.h"
#include "wifi_wlfw.h"
#include "wifi_bdf.h"
static struct rf_bdf_session state;
static struct rf_wlfw_cap expected;
static uint8_t bdf[RF_BDF_BYTES],packets[32][RF_BDF_PACKET];
static uint32_t lengths[32],sends,checks,fail_check,fail_send,alive;
static int check(void *p){++checks;return p!=&state || !alive || (fail_check && checks>=fail_check) ? -1 : 0;}
static int send(void *p,const uint8_t *data,uint32_t bytes){
 if(p!=&state || bytes>RF_BDF_PACKET || sends>=32)return -1;
 memcpy(packets[sends],data,bytes);lengths[sends++]=bytes;
 return fail_send && sends==fail_send ? -1 : 0;
}
static const struct rf_bdf_ops ops={&state,check,send};
void reset(void){
 memset(&state,0,sizeof(state));memset(packets,0,sizeof(packets));memset(lengths,0,sizeof(lengths));
 memset(&expected,0,sizeof(expected));expected.valid=13;expected.chip=0x4320;expected.family=0x4001;
 expected.soc=0x400b0000;expected.firmware=0x33197fff;
 for(unsigned i=0;i<sizeof(bdf);++i)bdf[i]=(uint8_t)(i*17+3);
 sends=checks=fail_check=fail_send=0;alive=1;
}
int begin(unsigned mode){
 if(mode==1)expected.chip^=1;if(mode==2){expected.valid|=2;expected.board=7;}
 if(mode==3)expected.valid=0;
 return rf_bdf_begin(&state,&ops,mode==4 ? NULL : bdf,RF_BDF_BYTES-(mode==5),&expected);
}
int receive(const uint8_t *p,uint32_t bytes){return rf_bdf_receive(&state,&ops,p,bytes);}
const uint8_t *packet(unsigned n){return n<32 ? packets[n] : NULL;}
uint32_t packet_bytes(unsigned n){return n<32 ? lengths[n] : 0;}
uint64_t metric(unsigned n){
 uint64_t values[]={state.stage,state.offset,state.segment,state.chunk,state.requests,state.responses,
 state.bdf_acks,state.cal_reported,state.fw_ready,state.msa_ready,state.poisoned,state.ignored,
 state.result,state.error,sends,checks,state.transaction,state.waiting,state.skipped_ready,state.indications};
 return n<sizeof(values)/sizeof(values[0]) ? values[n] : 0;
}
void option(unsigned which,unsigned value){if(!which)fail_check=value;if(which==1)fail_send=value;if(which==2)alive=value;}
int direct(unsigned stage){return rf_bdf_send(&state,&ops,stage);}
'''
        (directory / 'bdf.c').write_text(source)
        result = subprocess.run(['cc', '-std=c11', '-shared', '-fPIC', '-Wall', '-Wextra', '-Werror',
                                 '-I', str(HERE), str(directory / 'bdf.c'), '-o', str(directory / 'bdf.so')], capture_output=True, text=True)
        if result.returncode:
            raise RuntimeError(result.stderr)
        cls.lib = C.CDLL(str(directory / 'bdf.so'))
        cls.lib.packet.restype = C.c_void_p; cls.lib.metric.restype = C.c_uint64
        cls.lib.receive.argtypes = [C.c_void_p, C.c_uint32]

    def setUp(self):
        self.lib.reset()

    def packet(self, index):
        return C.string_at(self.lib.packet(index), self.lib.packet_bytes(index))

    def receive(self, message, transaction, extra=b'', *, result=0, error=0, indication=False):
        data = response(message, transaction, extra, result=result, error=error, indication=indication)
        return self.lib.receive(data, len(data))

    def started(self):
        self.assertEqual(self.lib.begin(0), 0)
        self.assertEqual(self.receive(0x20, 1, tlv(0x10, struct.pack('<Q', 4))), 0)
        self.assertEqual(self.receive(0x24, 2, identity()), 0)

    def drive(self):
        """Drive only legal replies; return the first core or QMI failure."""
        code = self.lib.begin(0)
        if code:
            return code
        code = self.receive(0x20, 1, tlv(0x10, struct.pack('<Q', 4)))
        if code:
            return code
        code = self.receive(0x24, 2, identity())
        if code:
            return code
        while self.lib.metric(0) == 4:
            code = self.receive(0x25, self.lib.metric(16))
            if code:
                return code
        return self.receive(0x26, self.lib.metric(16)) if self.lib.metric(0) == 5 else -1

    def test_separate_dmon_registration_uses_native_client_id_and_waits_for_actual_msa(self):
        self.assertEqual(self.lib.begin(0), 0)
        self.assertEqual(fields(self.packet(0)), {0x10: b'\1', 0x13: b'\1', 0x15: struct.pack('<I', 0x444d4f4e)})
        self.assertEqual(self.receive(0x20, 1), 0)
        self.assertEqual((self.lib.metric(0), self.lib.metric(14)), (2, 1))
        self.assertEqual(self.receive(0x2b, 0, indication=True), 0)
        self.assertEqual((self.lib.metric(0), self.lib.metric(14)), (3, 2))
        self.assertEqual(self.packet(1), struct.pack('<BHHH', 0, 2, 0x24, 0))

    def test_all_exact_board_bytes_follow_checked_acks_full_total_and_one_final_end_flag(self):
        self.started(); assembled = bytearray()
        for index in range(13):
            packet = self.packet(index + 2); values = fields(packet)
            self.assertEqual(struct.unpack_from('<BHHH', packet), (0, index + 3, 0x25, len(packet) - 7))
            self.assertEqual(set(values), {1, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15})
            self.assertEqual(values[1], b'\1'); self.assertEqual(values[0x10], bytes(4))
            self.assertEqual(struct.unpack('<I', values[0x11])[0], len(BDF))
            self.assertEqual(struct.unpack('<I', values[0x12])[0], index)
            chunk = values[0x13]; self.assertEqual(struct.unpack_from('<H', chunk)[0], len(chunk) - 2)
            self.assertLessEqual(len(chunk) - 2, 2048); assembled += chunk[2:]
            self.assertEqual(values[0x14], bytes([index == 12])); self.assertEqual(values[0x15], b'\0')
            self.assertEqual(self.lib.metric(1), index * 2048)
            self.assertEqual(self.receive(0x25, index + 3), 0)
        self.assertEqual(bytes(assembled), BDF)
        self.assertEqual([self.lib.metric(i) for i in (0, 1, 6, 7, 8)], [5, len(BDF), 13, 0, 0])
        self.assertEqual(fields(self.packet(15)), {1: b'\0', 0x11: b'\0'})
        self.assertEqual(self.receive(0x26, 16), 0)
        self.assertEqual([self.lib.metric(i) for i in (0, 7, 8, 14)], [6, 1, 0, 16])
        self.assertEqual(self.receive(0x21, 0, indication=True), 0)
        self.assertEqual(self.lib.metric(8), 1)

    def test_bad_kernel_or_fresh_daemon_identity_cannot_send_board_bytes(self):
        for mode in range(1, 6):
            self.setUp(); self.assertNotEqual(self.lib.begin(mode), 0); self.assertEqual(self.lib.metric(14), 0)
        for extra in (identity(chip=0x4321), identity(board=1), b'', identity() + tlv(0x10, bytes(8))):
            self.setUp(); self.assertEqual(self.lib.begin(0), 0)
            self.assertEqual(self.receive(0x20, 1, tlv(0x10, struct.pack('<Q', 4))), 0)
            self.assertNotEqual(self.receive(0x24, 2, extra), 0)
            self.assertEqual(self.lib.metric(14), 2); self.assertEqual(self.lib.metric(1), 0)

    def test_duplicates_foreign_transactions_and_late_acks_never_advance_or_resend(self):
        self.started()
        for message, transaction in ((0x24, 2), (0x25, 99), (0x26, 3)):
            self.assertEqual(self.receive(message, transaction), 1)
        self.assertEqual((self.lib.metric(1), self.lib.metric(14)), (0, 3))
        self.assertEqual(self.receive(0x25, 3), 0)
        self.assertEqual(self.receive(0x25, 3), 1)
        self.assertEqual((self.lib.metric(1), self.lib.metric(14)), (2048, 4))
        for stage in range(8):
            self.assertNotEqual(self.lib.direct(stage), 0)
        self.assertEqual(self.lib.metric(14), 4)

    def test_all_qmi_rejections_including_final_crc_error_stop_before_cal_report_without_retry(self):
        for index in range(13):
            self.setUp(); self.started()
            for previous in range(index):
                self.assertEqual(self.receive(0x25, previous + 3), 0)
            self.assertEqual(self.receive(0x25, index + 3, result=1, error=1), 0)
            self.assertEqual([self.lib.metric(i) for i in (0, 1, 6, 7, 12, 13)], [7, index * 2048, index, 0, 1, 1])
            sent = self.lib.metric(14)
            self.assertNotEqual(self.lib.begin(0), 0)
            self.assertEqual(self.receive(0x25, index + 3), 1)
            self.assertEqual(self.lib.metric(14), sent)

    def test_every_owner_check_and_send_uncertainty_stops_further_requests(self):
        self.assertEqual(self.drive(), 0); checks = self.lib.metric(15)
        for at in range(1, checks + 1):
            self.setUp(); self.lib.option(0, at)
            self.assertNotEqual(self.drive(), 0)
            sent = self.lib.metric(14); self.assertEqual(self.lib.metric(10), 1)
            self.assertNotEqual(self.lib.begin(0), 0)
            self.assertEqual(self.lib.metric(14), sent)
        for at in range(1, 17):
            self.setUp(); self.lib.option(1, at)
            self.assertNotEqual(self.drive(), 0)
            self.assertEqual((self.lib.metric(14), self.lib.metric(10)), (at, 1))

    def test_already_registered_without_ready_is_refused_and_real_ready_does_not_invent_a_download(self):
        self.assertEqual(self.lib.begin(0), 0)
        self.assertEqual(self.receive(0x20, 1, tlv(0x10, struct.pack('<Q', 1))), 0)
        self.assertEqual((self.lib.metric(0), self.lib.metric(14)), (7, 1))
        self.setUp(); self.assertEqual(self.lib.begin(0), 0)
        self.assertEqual(self.receive(0x20, 1, tlv(0x10, struct.pack('<Q', 3))), 0)
        self.assertEqual([self.lib.metric(i) for i in (0, 1, 8, 14, 18)], [6, 0, 1, 1, 1])

    def test_malformed_replies_and_rejuvenation_never_advance_and_readiness_is_independent(self):
        for extra in (tlv(2, bytes(4)), tlv(0x10, b'\1'), tlv(1, b'\1')):
            self.setUp(); self.assertEqual(self.lib.begin(0), 0)
            self.assertNotEqual(self.receive(0x20, 1, extra), 0)
            self.assertEqual(self.lib.metric(14), 1)
        self.setUp(); self.started()
        self.assertEqual(self.receive(0x21, 0, indication=True), 0)
        self.assertEqual((self.lib.metric(0), self.lib.metric(1), self.lib.metric(8)), (4, 0, 1))
        self.assertNotEqual(self.receive(0x39, 0, indication=True), 0)
        self.assertEqual((self.lib.metric(0), self.lib.metric(10)), (7, 1))


class WiFiBdfProducerTests(unittest.TestCase):
    def test_board_selection_is_explicit_and_requires_native_power(self):
        source = source_nodes(); root = mkadt.build(0x180000000, 0x80000000)
        P.add_wlfw_contract(root, source)
        with self.assertRaises(ValueError):
            P.add_wlan_observer_contract(root, source, bdf=True)
        P.add_wlan_observer_contract(root, source, power=True, bdf=True)
        node = next(node for node in root.children if node.name == 'redfin-wifi-wlan')
        self.assertEqual(node.prop('bdf-download'), b'\1\0\0\0')
        self.assertEqual(node.prop('bdf-name'), b'image/bdwlan-u-redfin.bin\0')
        self.assertEqual(struct.unpack('<8I', node.prop('bdf-contract')), (1, 0x444d4f4e, 0x4005, 26328, 2048, 0x4320, 0xff, 0))


if __name__ == '__main__':
    unittest.main()
